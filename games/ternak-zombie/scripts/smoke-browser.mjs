import path from 'node:path';
import { browserHarness, watchErrors, artifacts } from './browser-harness.mjs';
import { status, driveTo } from './zombie-actions.mjs';

const zombies = state => JSON.parse(state.zombies);
await browserHarness(async ({ browser, server, assert }) => {
  for (const [name, touch] of [['keyboard', false], ['touch', true]]) {
    const context = await browser.newContext({ viewport: touch ? { width: 390, height: 844 } : { width: 1366, height: 900 }, hasTouch: true });
    const page = await context.newPage();
    const errors = watchErrors(page, server.origin);
    await page.goto(server.url);
    await page.locator('#start-button').click();
    const initial = await status(page);
    assert.equal(Number(initial.captiveCount), 0, 'fresh run has no captives');
    assert.equal(Number(initial.energy), 0, 'no free electricity');
    await page.locator('#lure-button').click();
    const baited = await status(page);
    assert.equal(Number(baited.bait), Number(initial.bait) - 1, 'bait action pays one bait');
    const target = zombies(baited).find(z => z.mode === 'lured');
    assert.ok(target, 'actual wild zombie is lured');
    if (touch) await driveTo(page, 865, 940, { touch });
    else await driveTo(page, 1120, 800, { touch });
    await driveTo(page, 865, 800, { touch });
    await page.waitForFunction(() => Number(document.querySelector('#game-status').dataset.captiveCount) >= 1, null, { timeout: 10000 });
    const captured = await status(page);
    const captive = zombies(captured).find(z => z.id === target.id);
    assert.ok(captive?.captive, 'the same zombie physically enters captivity');
    assert.ok(Math.abs(captive.x - Number(captured.cageX)) <= Number(captured.cageWidth) / 2 && Math.abs(captive.y - Number(captured.cageY)) <= Number(captured.cageHeight) / 2, 'captive position is inside cage');
    assert.ok(Math.hypot(captive.x - target.x, captive.y - target.y) > 100, 'zombie traversed the world before capture');
    await page.waitForTimeout(800);
    const producing = await status(page);
    const moved = zombies(producing).find(z => z.id === target.id);
    assert.ok(Math.hypot(moved.x - captive.x, moved.y - captive.y) > 1, 'captive actually moves');
    assert.ok(Number(producing.totalGenerated) > Number(captured.totalGenerated) && Number(producing.energy) > 0 && Number(producing.generation) > 0, 'physical movement produces battery energy');
    await page.screenshot({ path: path.join(artifacts, `${name}-capture-energy.png`), fullPage: true });
    await driveTo(page, 1080, 800, { touch });
    await page.locator('#generator-button').click();
    const stopped = await status(page);
    await page.waitForTimeout(500);
    const rested = await status(page);
    assert.equal(Number(rested.generation), 0, 'generator off produces zero');
    assert.equal(rested.totalGenerated, stopped.totalGenerated, 'off generator earns nothing');
    assert.deepEqual(zombies(rested).filter(z => z.captive), zombies(stopped).filter(z => z.captive), 'off generator rests actual captives');
    await page.locator('#generator-button').click();
    await page.locator('#pause-button').click();
    const paused = await status(page);
    await page.keyboard.down('ArrowRight');
    await page.waitForTimeout(400);
    await page.keyboard.up('ArrowRight');
    const frozen = await status(page);
    for (const key of ['playerX', 'playerY', 'energy', 'totalGenerated', 'zombies']) assert.equal(frozen[key], paused[key], `pause freezes ${key}`);
    await page.locator('#resume-button').click();
    const cage = JSON.parse((await status(page)).upgradeZones).find(zone => zone.kind === 'cage');
    assert.equal(Number(cage.duration), 10, 'first Kinetik upgrade takes ten seconds');
    await driveTo(page, 1080, 940, { touch });
    await driveTo(page, cage.x, 940, { touch });
    const upgradeBefore = await status(page);
    await driveTo(page, cage.x, cage.y, { touch });
    await page.waitForTimeout(1600);
    const building = await status(page);
    assert.equal(building.constructionKind, 'cage');
    assert.ok(Number(building.constructionProgress) > 0 && Number(building.constructionProgress) < Number(building.constructionDuration));
    assert.equal(Number(building.scrap), Number(upgradeBefore.scrap) - Number(cage.cost), 'pad charges once at start');
    assert.equal(building.cageCapacity, upgradeBefore.cageCapacity, 'capacity waits for completion');
    assert.ok(await page.locator('#construction-status').isVisible(), 'active ground-pad progress is visible');
    assert.ok(Number(await page.locator('#construction-progress').getAttribute('value')) > 0, 'progress indicator advances');
    await page.screenshot({ path: path.join(artifacts, `${name}-upgrading.png`), fullPage: true });
    await driveTo(page, cage.x, 940, { touch });
    const outside = await status(page);
    await page.waitForTimeout(450);
    assert.equal((await status(page)).constructionProgress, outside.constructionProgress, 'leaving pad holds progress');
    await driveTo(page, cage.x, cage.y, { touch });
    assert.equal((await status(page)).scrap, building.scrap, 'returning does not charge twice');
    await page.waitForFunction(() => Number(document.querySelector('#game-status').dataset.cageLevel) === 1, null, { timeout: 12000 });
    const upgraded = await status(page);
    assert.equal(Number(upgraded.cageCapacity), Number(upgradeBefore.cageCapacity) + 2);
    assert.equal(Number(JSON.parse(upgraded.upgradeZones).find(zone => zone.kind === 'cage').duration), 20);
    await driveTo(page, cage.x, 940, { touch });
    // Real supplies fund the timed wall without bypassing resources.
    for (const [x, y] of [[710, 1060], [1430, 1030]]) {
      await driveTo(page, x, 940, { touch });
      await driveTo(page, x, y, { touch });
      const before = await status(page);
      await page.locator('#interact-button').click();
      assert.equal(Number((await status(page)).scrap), Number(before.scrap) + 5, 'real exploration collects supplies');
      await driveTo(page, x, 940, { touch });
    }
    const wall = JSON.parse((await status(page)).upgradeZones).find(zone => zone.kind === 'walls');
    await driveTo(page, wall.x, 940, { touch });
    const buildBefore = await status(page);
    assert.equal(Number(buildBefore.wallLevel), 0, 'wall is initially absent');
    await driveTo(page, wall.x, wall.y, { touch });
    await page.waitForTimeout(500);
    const wallBuilding = await status(page);
    assert.equal(wallBuilding.constructionKind, 'walls');
    assert.equal(Number(wallBuilding.constructionDuration), 8);
    assert.equal(Number(wallBuilding.scrap), Number(buildBefore.scrap) - Number(wall.cost));
    assert.equal(Number(wallBuilding.wallLevel), 0, 'wall waits for completion');
    await page.waitForFunction(() => Number(document.querySelector('#game-status').dataset.wallLevel) === 1, null, { timeout: 10000 });
    const built = await status(page);
    assert.ok(Number(built.wallHp) > 0 && Number(built.maxWallHp) >= Number(built.wallHp), 'completed wall has actual HP');
    const completedTitle = await page.locator('#construction-title').textContent();
    assert.match(completedTitle, /LV 1\s*✓/, 'completed wall reports its current level');
    assert.doesNotMatch(completedTitle, /→\s*2/, 'holding completed pad does not show the next job');
    const completedProgress = await page.locator('#construction-progress').evaluate(element => ({ value: element.value, max: element.max }));
    assert.equal(completedProgress.value, completedProgress.max, 'completed wall progress stays at 100 percent');
    await page.screenshot({ path: path.join(artifacts, `${name}-completed-wall.png`), fullPage: true });
    await page.locator('#pause-button').click();
    await page.locator('#restart-button').click();
    await page.locator('#confirm-restart-button').click();
    const restarted = await status(page);
    assert.equal(Number(restarted.captiveCount), 0, 'restart clears captivity');
    assert.equal(Number(restarted.energy), 0, 'restart clears battery');
    assert.equal(Number(restarted.scrap), Number(initial.scrap), 'restart restores initial supplies');
    assert.deepEqual(errors, [], `${name}: browser/network errors`);
    await context.close();
  }
  console.log('Production mechanics smoke passed: keyboard/touch capture from two sides, energy, rest, pause, timed zone payment/resume, wall HP and reset.');
});
